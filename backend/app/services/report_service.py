        f"The stock's 30-day quantitative machine learning model projects an upper boundary of ₹{ml_forecast['forecast_30d']['range_high']:,.2f}, "
        f"with a baseline target of ₹{target_2:,.2f}. If corporate balance sheet strength and domestic order execution continue "
        f"their current trajectory, a retest of the 52-week peak at ₹{week52_high:,.2f} remains mathematically viable within the cyclical horizon."
