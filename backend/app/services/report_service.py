def _compute_pivot_levels(current_price: float, high: float, low: float, prev_close: float) -> Dict[str, float]:
    """Calculate classic pivot points & support/resistance levels."""
    h = max(high, current_price)
    l = min(low, current_price)
    c = current_price if current_price > 0 else prev_close
    
    pivot = (h + l + c) / 3.0
    r1 = (2 * pivot) - l
    s1 = (2 * pivot) - h
    r2 = pivot + (h - l)
    s2 = pivot - (h - l)
    
    return {
        "pivot": round(pivot, 2),
        "r1": round(r1, 2),
        "r2": round(r2, 2),
        "s1": round(s1, 2),
        "s2": round(s2, 2),
    }


